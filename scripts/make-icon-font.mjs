// Builds public/fonts/tabler-subset.{woff2,css} — the icon font, cut down to the
// icons the PUBLIC pages actually use.
//
// Why: every visitor to the marketing site downloaded the full Tabler webfont
// from a CDN — 803 KB of font plus 37 KB of CSS for ~5,900 icons, of which the
// public pages use about fifty (measured with Lighthouse on 2026-09-18: 4.2 MB
// page weight, 7.8 s largest paint on a phone). The subset is a few kilobytes
// and is served from our own domain, so there is no second connection to open.
//
// The dashboard and the admin panel keep the full font from the CDN (their own
// layout adds it): they use hundreds of icons, they are behind a login, and a
// logged-in user loads it once and keeps it cached.
//
// Run it with:  node scripts/make-icon-font.mjs
// Needs Python with fonttools + brotli:  python -m pip install fonttools brotli
// The output is committed; re-run it when a public page starts using an icon
// that is not in the list (the script prints what it found).

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, rmSync } from "node:fs";
import { dirname, join, extname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ROOT, "public", "fonts");
const VERSION = "3.6.0";
const CDN = `https://cdn.jsdelivr.net/npm/@tabler/icons-webfont@${VERSION}/dist`;

// Where public markup lives. The dashboard, admin, preview and screenshot
// studio are deliberately not here — they keep the full font.
const SCAN = [
  "src/app/page.js", "src/app/site-shell.js", "src/app/docs", "src/app/pricing",
  "src/app/contact", "src/app/privacy", "src/app/terms", "src/app/google-calendar",
  "src/app/solutions", "src/lib/landing.js", "src/lib/docs", "src/lib/solutions",
  "src/lib/connect-page.js",
];

function walk(p, out = []) {
  const full = join(ROOT, p);
  const st = statSync(full, { throwIfNoEntry: false });
  if (!st) return out;
  if (st.isDirectory()) { for (const e of readdirSync(full)) walk(join(p, e), out); return out; }
  if ([".js", ".jsx", ".mjs"].includes(extname(full))) out.push(readFileSync(full, "utf8"));
  return out;
}

const source = SCAN.flatMap((p) => walk(p)).join("\n");
const used = [...new Set([...source.matchAll(/\bti-[a-z0-9-]+/g)].map((m) => m[0]))]
  .filter((n) => n !== "ti-" && n.length > 3).sort();

const css = await fetch(`${CDN}/tabler-icons.min.css`).then((r) => r.text());
// .ti-name:before{content:"\eabc"}
const map = new Map();
for (const m of css.matchAll(/\.(ti-[a-z0-9-]+):+before\s*\{\s*content:\s*"\\([0-9a-f]+)"/gi)) map.set(m[1], m[2]);

const found = used.filter((n) => map.has(n));
const missing = used.filter((n) => !map.has(n));
if (missing.length) console.log("not in the icon font (check the name):", missing.join(", "));

const codepoints = found.map((n) => `U+${map.get(n).toUpperCase()}`);
mkdirSync(OUT, { recursive: true });

const woff2 = Buffer.from(await fetch(`${CDN}/fonts/tabler-icons.woff2`).then((r) => r.arrayBuffer()));
const tmpIn = join(OUT, ".tabler-full.woff2");
writeFileSync(tmpIn, woff2);

execFileSync("python", [
  "-m", "fontTools.subset", tmpIn,
  `--unicodes=${codepoints.join(",")}`,
  "--flavor=woff2",
  // The Tabler build ships a GSUB table fontTools cannot read (it asserts on
  // the ligature sets). Icon fonts do not need shaping tables at all — each
  // glyph is addressed by its own codepoint — so they are dropped.
  "--drop-tables+=GSUB,GPOS",
  "--layout-features=",
  `--output-file=${join(OUT, "tabler-subset.woff2")}`,
], { stdio: "inherit" });

// The same class names the markup already uses, so no page changes.
const rules = found.map((n) => `.${n}:before{content:"\\${map.get(n)}"}`).join("\n");
writeFileSync(join(OUT, "tabler-subset.css"), `/* Generated by scripts/make-icon-font.mjs from @tabler/icons-webfont ${VERSION}.
   ${found.length} icons — the ones the public pages use. Do not edit by hand. */
@font-face{font-family:"tabler-icons";font-style:normal;font-weight:400;font-display:swap;src:url("/fonts/tabler-subset.woff2") format("woff2")}
.ti{font-family:"tabler-icons"!important;font-style:normal;font-weight:400!important;font-variant:normal;text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale;display:inline-block}
${rules}
`);

const full = statSync(tmpIn).size, small = statSync(join(OUT, "tabler-subset.woff2")).size;
// The full font must not stay in public/ — anything there is served.
rmSync(tmpIn, { force: true });
console.log(`${found.length} icons · ${(full / 1024).toFixed(0)} KB → ${(small / 1024).toFixed(1)} KB`);
